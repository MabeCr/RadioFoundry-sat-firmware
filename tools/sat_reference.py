"""Reference values for the satellite host test (tests/host/satTest.c, docs/spec/satellite.md 8).

Runs two MIT-licensed libraries as black boxes on the PC: python-sgp4 for the TEME states, Skyfield for look angles
and passes (its own sidereal time, polar motion and UT1, so it checks our simpler frames too). Writes
tests/host/sat_ref.h, which is committed: the host tests don't need Python.

    pip install sgp4 skyfield
    python3 tools/sat_reference.py
"""
import datetime
import pathlib
import sys

from sgp4.api import Satrec, WGS72
from skyfield.api import EarthSatellite, load, wgs84

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "tests/host/sat_ref.h"


def fix(line):
    """Recompute a line's check digit (the elements below are edited by hand)"""
    s = sum(int(c) if c.isdigit() else (1 if c == "-" else 0) for c in line[:68])
    return line[:68] + str(s % 10)


# Element sets: real orbits, epochs moved near the test dates. The last two exercise the model's corners
TLES = [
    ("ISS", "1 25544U 98067A   26300.51782528  .00016717  00000-0  30144-3 0  9990",
     "2 25544  51.6416 247.4627 0006703 130.5360 325.0288 15.49815361474550"),
    ("SO-50", "1 27607U 02058C   26301.20512011  .00000825  00000-0  11606-3 0  9990",
     "2 27607  64.5560 140.2232 0048032 102.6391 257.9944 14.79391854261020"),
    ("AO-91", "1 43017U 17073E   26300.84023112  .00001244  00000-0  10731-3 0  9990",
     "2 43017  97.5918 252.9100 0234510  45.3011 316.7731 14.81624361476000"),
    # Perigee under 220 km: the simplified drag terms
    ("LOW", "1 99001U 26999A   26300.50000000  .01000000  00000-0  50000-3 0  9990",
     "2 99001  51.6300 100.0000 0090000  80.0000 280.0000 16.20000000000010"),
    # Alpha-5 catalog number (A0001 = 100001), near-circular
    ("A5", "1 A0001U 26999B   26300.50000000  .00000100  00000-0  10000-4 0  9990",
     "2 A0001  97.4000  10.0000 0001000   0.0000  90.0000 15.20000000000010"),
]
TLES = [(n, fix(a), fix(b)) for n, a, b in TLES]
TSINCE = [-1440.0, -360.0, 0.0, 90.0, 360.0, 720.0, 1440.0, 2880.0, 4320.0]
# The observer: Boulder, Colorado, 1650 m
OBS = (40.015, -105.27, 1650.0)


def c_str(s):
    return '"' + s + '"'


def main():
    ts = load.timescale(builtin=True)
    out = []
    w = out.append
    w("// SPDX-License-Identifier: MIT")
    w("// Copyright (c) 2026 The RadioFoundry Authors")
    w("// Generated by tools/sat_reference.py (python-sgp4 and Skyfield); don't edit")
    w("#ifndef SAT_REF_H")
    w("#define SAT_REF_H")
    w("")
    w("typedef struct { const char *name, *l1, *l2; } ref_tle_t;")
    w("typedef struct { int tle; double tsince; double r[3], v[3]; } ref_state_t;")
    w("typedef struct { int tle; double unix_s; double az, el, range, range_rate; } ref_look_t;")
    w("typedef struct { int tle; double from, aos, tca, los, max_el; } ref_pass_t;")
    w("")
    w(f"static const double ref_obs[3] = {{ {OBS[0]!r}, {OBS[1]!r}, {OBS[2]!r} }};")
    w("static const ref_tle_t ref_tles[] = {")
    for n, a, b in TLES:
        w(f"\t{{ {c_str(n)}, {c_str(a)}, {c_str(b)} }},")
    w("};")

    w("static const ref_state_t ref_states[] = {")
    for i, (_, a, b) in enumerate(TLES):
        sat = Satrec.twoline2rv(a, b, WGS72)
        for t in TSINCE:
            err, r, v = sat.sgp4_tsince(t)
            if err:
                continue
            w(f"\t{{ {i}, {t!r}, {{ {r[0]!r}, {r[1]!r}, {r[2]!r} }}, {{ {v[0]!r}, {v[1]!r}, {v[2]!r} }} }},")
    w("};")

    topos = wgs84.latlon(OBS[0], OBS[1], elevation_m=OBS[2])
    looks, passes = [], []
    for i, (_, a, b) in enumerate(TLES[:3]):
        es = EarthSatellite(a, b, ts=ts)
        t0 = es.epoch.utc_datetime().timestamp()
        # Look angles every 7 minutes over a day, above and below the horizon
        for k in range(0, 24 * 60, 7):
            u = t0 + k * 60.0 + 17.0
            t = ts.from_datetime(datetime.datetime.fromtimestamp(u, datetime.timezone.utc))
            rel = (es - topos).at(t)
            alt, az, dist, _, _, rr = rel.frame_latlon_and_rates(topos)
            looks.append((i, u, az.degrees, alt.degrees, dist.km, rr.km_per_s))
        # Every pass over two days from the epoch
        t1 = ts.from_datetime(es.epoch.utc_datetime() + datetime.timedelta(days=2))
        times, events = es.find_events(topos, es.epoch, t1, altitude_degrees=0.0)
        cur = {}
        for t, e in zip(times, events):
            cur[e] = t
            if e == 2 and 0 in cur and 1 in cur:
                alt = (es - topos).at(cur[1]).altaz()[0].degrees
                passes.append((i, cur[0].utc_datetime().timestamp(), cur[1].utc_datetime().timestamp(),
                               cur[2].utc_datetime().timestamp(), alt))
                cur = {}

    w("static const ref_look_t ref_looks[] = {")
    for i, u, az, el, rng, rr in looks:
        w(f"\t{{ {i}, {u!r}, {az:.6f}, {el:.6f}, {rng:.6f}, {rr:.9f} }},")
    w("};")
    w("// Each pass, searched from 10 minutes before its rise")
    w("static const ref_pass_t ref_passes[] = {")
    for i, aos, tca, los, el in passes:
        w(f"\t{{ {i}, {aos - 600.0:.3f}, {aos:.3f}, {tca:.3f}, {los:.3f}, {el:.4f} }},")
    w("};")
    w("")
    w("#endif")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(TLES)} element sets, {len(looks)} looks, {len(passes)} passes")


if __name__ == "__main__":
    sys.exit(main())
